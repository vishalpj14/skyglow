# Regenerates the public showcase from the real program.
#
# For every example place (examples/places/<name>.json) it runs the skyglow
# command-line tool on the two solstices and saves what the program printed
# into ONE file per place: examples/showcase/<name>.txt. Nothing is written by
# hand, and your private test/ folder is never read.
#
# Run from anywhere:
#     powershell -File examples\make-showcase.ps1
#
# The clock used on each day is the one a local wall clock would show:
# standard time, or daylight saving time if the place has it and it is in
# effect (northern places in June, southern places in December).

$ErrorActionPreference = "Stop"
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$OutputEncoding = [System.Text.Encoding]::UTF8
$inv = [System.Globalization.CultureInfo]::InvariantCulture

$repo = Split-Path -Parent $PSScriptRoot
Set-Location $repo

Write-Host "Building skyglow..."
cargo build -q -p skyglow-core
if ($LASTEXITCODE -ne 0) { throw "cargo build failed" }
$exe = Join-Path $repo "target\debug\skyglow.exe"
$placesDir = Join-Path $repo "examples\places"

$showcase = Join-Path $repo "examples\showcase"
New-Item -ItemType Directory -Force -Path $showcase | Out-Null
# Remove old showcase files so renamed or deleted places do not linger.
Get-ChildItem $showcase -Filter *.txt -ErrorAction SilentlyContinue | Remove-Item

$days = @(
    @{ date = "2026-12-21"; label = "December solstice" },
    @{ date = "2026-06-21"; label = "June solstice" }
)

foreach ($file in Get-ChildItem $placesDir -Filter *.json | Sort-Object Name) {
    $name = $file.BaseName
    $p = Get-Content $file.FullName -Raw | ConvertFrom-Json
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("Skyglow showcase: $($p.name)")
    $lines.Add("Generated by examples/make-showcase.ps1 from the real program. Nothing edited by hand.")
    if ($p.note) { $lines.Add("About this place: $($p.note)") }

    foreach ($d in $days) {
        $tz = [double]$p.tz
        # Daylight saving: June in the north, December in the south.
        if ($p.dst_tz) {
            $summerInNorth = ($d.date -like "*-06-21")
            if (($p.lat -ge 0 -and $summerInNorth) -or ($p.lat -lt 0 -and -not $summerInNorth)) {
                $tz = [double]$p.dst_tz
            }
        }
        $tzArg = $tz.ToString($inv)
        $lines.Add("")
        $lines.Add(("=" * 72))
        $lines.Add("$($d.label)  ($($d.date))")
        $lines.Add(("=" * 72))
        $out = & $exe --place $name $d.date --tz $tzArg --places $placesDir 2>&1
        if ($LASTEXITCODE -ne 0) { throw "skyglow failed for $name on $($d.date): $out" }
        foreach ($l in $out) { $lines.Add([string]$l) }
    }

    $target = Join-Path $showcase "$name.txt"
    [System.IO.File]::WriteAllLines($target, $lines, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "  wrote examples\showcase\$name.txt"
}
Write-Host "Done."
